/**
 * Всё, что нужно странице, одним объектом. Нет такой страницы или парка
 * в parks.js — пусто, страница скажет об этом честной надписью.
 */
export function popolnitPage (slug) {
  const cfg = POPOLNIT_PAGES[slug]
  if (!cfg) return null
  const p = parks.find((x) => x.id === cfg.park)
  if (!p) return null
  const lk = (p.lk && p.lk.status === 'active' && p.lk.url) || ''
  return {
    ...cfg,
    name: p.name,
    accent: p.accent,
    lk,
    /* Кабинета нет в parks.js — кнопку не рисуем, даже если флаг включён. */
    online: !!(cfg.online && lk),
    offers: OFFERS.map((o) => {
      const gift = giftFor(o.sum)
      let tickets = 0
      for (const t of cfg.cashTickets || []) if (o.sum >= t.from) tickets = t.tickets
      return { ...o, gift, onCard: o.sum + gift, games: gamesFor(gift), tickets }
    }),
    steps: STEPS.filter((s) => s.sum >= cfg.stepsFrom)
  }
}
