/* ── Подарок за пополнение ───────────────────────────────────────────────
   Подарок начисляется за ИНТЕРВАЛ суммы: от `sum` до следующей ступени.
   500–999 → +125 · 1 000–1 499 → +300 · 1 500–1 999 → +525 ·
   2 000–2 999 → +800 · 3 000–4 999 → +1 500 · от 5 000 → +3 000.
   Поэтому 1 400 ₽ дают +300, а 1 500 ₽ — уже +525. */
export const STEPS = [
  { sum: 500,  gift: 125 },
  { sum: 1000, gift: 300 },
  { sum: 1500, gift: 525 },
  { sum: 2000, gift: 800 },
  { sum: 3000, gift: 1500 },
  { sum: 5000, gift: 3000 }
]

/** Подарок за сумму: ступень, в интервал которой сумма попала. Меньше 500 — 0. */
export function giftFor (sum) {
  let gift = 0
  for (const s of STEPS) if (sum >= s.sum) gift = s.gift
  return gift
}

/* Средняя цена игры, ₽ — та же, что на b00m.fun/rewards («≈ расчёт при
   средней цене игры ~70₽»), решение владельца 01.10. «≈ +7 игр» в карточке =
   подарок / GAME_PRICE, вниз до целого. Та же цифра — game_price в
   boom-cmd/media/kassa/kassa.data.json (ТВ-экран). */
export const GAME_PRICE = 70

/** Сколько игр даёт подарок, вниз до целого. */
export function gamesFor (gift) {
  return Math.floor(gift / GAME_PRICE)
}

/* 1 игра · 2 игры · 7 игр · 21 игра · 42 игры */
export function plural (n, one, few, many) {
  const a = n % 10
  const b = n % 100
  if (a === 1 && b !== 11) return one
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return few
  return many
}

